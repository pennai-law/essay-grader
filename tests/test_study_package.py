# ---- MCQ workbook parity rules -------------------------------------------------------------------------------------
KEY = {1: "B", 2: "B", 3: "B", 4: "A", 5: "A"}


def _wb(tmp_path):
    wb, totals = build_workbook("Introductory Widget Law", "Quill", KEY,
                                [(137, parse_submission(CLEAN_MCQ)), (460, parse_submission("1. B\n2. A\n3. B\n4. C\n5. A\n"))])
    p = tmp_path / "x.xlsx"
    wb.save(p)
    return openpyxl.load_workbook(p), totals


def test_mcq_workbook_layout_and_case_encoding(tmp_path):
    wb, totals = _wb(tmp_path)
    ws = wb.active
    assert ws.title == "ET_Results_Introductory_Widget_Law_(Quill)_P"[:31] == mcq_sheet_name("Introductory Widget Law", "Quill")
    rows = [[c.value for c in r] for r in ws.iter_rows()]
    assert rows[0] == ["Exam #", "Pts", "Q1", "Q1 Pts", "Q2", "Q2 Pts", "Q3", "Q3 Pts", "Q4", "Q4 Pts", "Q5", "Q5 Pts"]
    assert rows[1] == ["ANSWER KEY -->", None, "B", None, "B", None, "B", None, "A", None, "A", None]  # blank Pts = key sentinel
    assert rows[2] == [137, 5, "B", 1, "B", 1, "B", 1, "A", 1, "A", 1]  # uppercase = correct
    assert rows[3] == [460, 3, "B", 1, "a", 0, "B", 1, "c", 0, "A", 1]  # lowercase = wrong, Pts 0
    assert totals == [(137, 5), (460, 3)] and isinstance(rows[2][0], int)


