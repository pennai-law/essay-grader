def test_answer_key_and_submission_parsing_and_validation():
    assert parse_answer_key("Q1: B\nQ2. c\nQ3) D\n") == {1: "B", 2: "C", 3: "D"}
    assert parse_answer_key("A,b, C") == {1: "A", 2: "B", 3: "C"}
    assert parse_submission("1. a\n2) B\nnoise\n") == {1: "A", 2: "B"}
    with pytest.raises(PackagingError, match="conflicting"):
        parse_answer_key("Q1: A\nQ1: B\n")
    with pytest.raises(PackagingError, match="missing"):
        build_workbook("C", "P", KEY, [(1, {1: "A", 2: "B"})])


