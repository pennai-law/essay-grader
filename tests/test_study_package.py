@pytest.mark.skipif(not xelatex_available(), reason="xelatex (TeX Live basic + xetex, Helvetica) not installed")
def test_pdfs_build_and_render_the_same_section_code_in_filename_and_body(design, store, protocol):
    import subprocess

    _generate(design, store)
    res = package_study(design, store, protocol)
    pdfs = [p for p in res.files if p.suffix == ".pdf"]
    assert len(pdfs) == 3
    if shutil.which("pdftotext"):
        for pdf in pdfs:
            body = subprocess.run(["pdftotext", "-layout", str(pdf), "-"], capture_output=True, text=True).stdout
            assert re.search(r"2026A", body) and not ARM_TELLS.search(body.replace("Introductory Widget Law", ""))
            assert pdf.name[:4] in body


