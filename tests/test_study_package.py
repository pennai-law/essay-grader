# ---- no arm tells --------------------------------------------------------------------------------------------------
def test_same_content_in_every_arm_yields_identical_packaging_except_the_id(design, store, protocol):
    _generate(design, store)
    res = package_study(design, store, protocol, build_pdfs=False)
    texs = {p.name.split("-")[0]: p.read_text() for p in res.tex_files}
    assert set(texs) == {"0137", "0460", "0891"}
    norm = {eid: t.replace(eid, "ID") for eid, t in texs.items()}
    assert len(set(norm.values())) == 1, "A, S and B documents with identical answers must be indistinguishable apart from the ID"


def test_filenames_and_metadata_carry_no_arm_model_or_materials_tells(design, store, protocol):
    _generate(design, store)
    res = package_study(design, store, protocol, build_pdfs=False)
    names = [p.name for p in res.tex_files] + [p.name for p in res.files]
    assert names and not any(ARM_TELLS.search(n) for n in names), names
    pat = re.compile(r"^\d{4}-Introductory_Widget_Law_\(Quill\)_2026A_\d{12}\.tex$")
    assert all(pat.match(p.name) for p in res.tex_files)
    assert {re.search(r"(20\d\d[A-Z])", n).group(1) for n in names if n.endswith(".tex")} == {"2026A"}  # one uniform term-section code, never the arm letter
    for p in res.tex_files:
        t = p.read_text()
        assert not ARM_TELLS.search(t.replace("Introductory Widget Law", "")), p.name
        assert "2026A" in t
    # the deliverables directory holds only registrar-shaped artifacts; the arm map lives outside it
    deliver = res.deliver_dir
    assert deliver.name == "deliver" and all(p.parent == deliver for p in res.files)
    man = json.loads((deliver.parent / "manifest.private.json").read_text())
    assert {d["arm"] for d in man["deliverables"]} == {"A", "S", "B"} and not (deliver / "manifest.private.json").exists()
    assert not any("manifest" in p.name for p in deliver.iterdir())


