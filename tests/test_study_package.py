def test_packaging_refuses_unconfirmed_examids_takehome_and_failing_audit(tmp_path):
    from essay_grader.study.protocol import Protocol

    def build(mutate, sub):
        d = Design.load(make_study(tmp_path / sub, mutate))
        st = StudyStore(tmp_path / sub / "out", d)
        _generate(d, st)
        return d, st, Protocol.load(d.path(d.protocol))

    d, st, p = build(lambda d: d["examid_policy"].update(confirmed=False), "a")
    with pytest.raises(PackagingError, match="confirmed is false"):
        package_study(d, st, p, build_pdfs=False)
    d, st, p = build(lambda d: d["exam"].update(delivery="take-home"), "b")
    with pytest.raises(PackagingError, match="take-home"):
        package_study(d, st, p, build_pdfs=False)
    d, st, p = build(lambda d: None, "c")
    d2 = d
    st2 = StudyStore(tmp_path / "c" / "out2", d2)
    _generate(d2, st2, script=lambda r: clean_script(r) + " Notably, yes." if r.cell_id == "q1__B__sonnet" else clean_script(r))
    with pytest.raises(PackagingError, match="fails the audit.*revise"):
        package_study(d2, st2, p, build_pdfs=False)


def test_packaging_builds_from_the_revised_pass_not_the_first_pass_capture(design, store, protocol):
    import asyncio

    from essay_grader.study.revise import revise_cell

    dirty = "Course materials are attached. " + CLEAN_ESSAY
    _generate(design, store, script=lambda r: dirty if r.cell_id == "q1__B__sonnet" else clean_script(r))
    with pytest.raises(PackagingError):
        package_study(design, store, protocol, build_pdfs=False)  # first-pass capture leaks the materials condition (L-043)
    asyncio.run(revise_cell(design, store, Cell("q1", "B", "sonnet"), protocol, citations=False))
    res = package_study(design, store, protocol, build_pdfs=False)
    tex = next(p for p in res.tex_files if p.name.startswith("0891")).read_text()
    assert "Course materials" not in tex and "Orbit's best claim" in tex
    assert json.loads((res.deliver_dir.parent / "manifest.private.json").read_text())["source_text"]["q1__B__sonnet"] == "revised"


