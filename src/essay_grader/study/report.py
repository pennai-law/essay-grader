"""Reports: a per-exam study report and a cohort dashboard DRAFT built from scoring-results.csv.

The dashboard is a generated draft (`cohort-results.draft.md`). exam-taker's real dashboard is human-curated; this file is
input to that curation, never a replacement. It follows the Wave 1 section 2 headline-table shape, generalized to arms
A/S/B/...: per exam and model, raw / rank / z per arm, and the z-score effect of each later arm over each earlier one.
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

from .design import Design
from .store import StudyStore


def _f(x, fmt="{:g}", dash="n/a"):
    return dash if x is None or x == "" else fmt.format(x)


def study_report(design: Design, store: StudyStore, analysis: dict | None = None) -> str:
    L = [f"# Study report: {design.exam.course} ({design.exam.professor}), {design.exam.term}", "",
         f"Study `{design.study_id}`. Generated by `essay-grader study report`; a draft for human curation.", "",
         "## Design", "",
         f"- Components: " + "; ".join(f"{c.id} ({c.kind}" + (f", ceiling {c.word_ceiling}" if c.word_ceiling else "")
                                        + (f", {c.n_questions} questions" if c.n_questions else "") + ")" for c in design.components),
         f"- Arms: " + ", ".join(f"{a.id} ({'no materials' if not a.materials else a.label or a.materials})" for a in design.arms),
         f"- Models: " + ", ".join(f"{m.key} = {m.model} ({m.provider})" for m in design.models),
         f"- Cells: {len(design.cells())}; captured: {len(store.captured_cells())}", ""]

    L += ["## Cells", "", "| Cell | Served model | Words | Audit (capture) | Revised | Cost USD |", "|---|---|---:|---|---|---:|"]
    spend = 0.0
    for c in design.cells():
        if not store.is_captured(c):
            L.append(f"| {c.id} | not captured | | | | |")
            continue
        meta = store.read_meta(c)
        ap = store.audit_path(c)
        audit = json.loads(ap.read_text(encoding="utf-8")) if ap.is_file() else None
        st = "not audited" if audit is None else ("pass" if audit["passed"] else f"FAIL ({audit['violations']})")
        rev = "yes" if store.revised_path(c).is_file() else "no"
        cost = meta.get("estimated_cost_usd") or 0.0
        spend += cost
        fb = " (FALLBACK)" if meta.get("model_fallback") else ""
        L.append(f"| {c.id} | {meta['served_model']}{fb} | {meta['words']} | {st} | {rev} | {cost:.4f} |")
    L += ["", f"Estimated generation spend: ${spend:.2f} (estimates; verify against billing).", ""]

    if analysis:
        L += ["## Scoring (real-student-only comparator; sample SD, n-1)", ""]
        for metric, m in analysis["metrics"].items():
            cs = m["class"]
            head = f"### {metric}" + (" (deterministic, AI only)" if m.get("deterministic") else "")
            L += [head, ""]
            if cs["n"]:
                L.append(f"Real students: n = {cs['n']}, mean {_f(cs['mean'], '{:.2f}')}, median {_f(cs['median'])}, "
                         f"SD {_f(cs['sd'], '{:.2f}')}, range {_f(cs['min'])}-{_f(cs['max'])}.")
                L.append("")
            L += ["| ExamID | Arm | Model | Raw | z | Rank (real only) | Percentile |", "|---|---|---|---:|---:|---:|---:|"]
            for e, a in sorted(m["ai"].items(), key=lambda kv: (kv[1]["arm"], kv[1]["model_key"])):
                rk = f"{a['rank_real_only']} of {a['n_real'] + 1}" + (" (tied)" if a.get("tied_with_real") else "") if a.get("rank_real_only") else "n/a"
                L.append(f"| {e} | {a['arm']} | {a['model_key']} | {_f(a['raw'])}" + (f"/{a['n_questions']}" if a.get("n_questions") else "")
                         + f" | {_f(a.get('z'), '{:+.2f}')} | {rk} | {_f(a.get('percentile'), '{:.0f}')} |")
            L.append("")
        L += ["## Arm contrasts (later minus earlier; rank negative = later arm ranks better)", "",
              "| Metric | Model | Contrast | Raw | z | Rank | SMD | Prop. diff | Odds ratio |", "|---|---|---|---:|---:|---:|---:|---:|---:|"]
        for c in analysis["arm_contrasts"]:
            L.append(f"| {c['metric']} | {c['model_key']} | {c['later_arm']} vs {c['earlier_arm']} | {_f(c['raw_diff'], '{:+g}')} | "
                     f"{_f(c['z_diff'], '{:+.2f}')} | {_f(c['rank_diff'], '{:+d}')} | {_f(c.get('smd'), '{:+.2f}')} | "
                     f"{_f(c.get('prop_diff'), '{:+.3f}')} | {_f(c.get('odds_ratio'), '{:.2f}')} |")
        if analysis["model_contrasts"]:
            L += ["", "## Model contrasts within arm (model_b minus model_a)", "", "| Metric | Arm | Models | Raw | z | Rank |", "|---|---|---|---:|---:|---:|"]
            for c in analysis["model_contrasts"]:
                L.append(f"| {c['metric']} | {c['arm']} | {c['model_b']} vs {c['model_a']} | {_f(c['raw_diff'], '{:+g}')} | "
                         f"{_f(c['z_diff'], '{:+.2f}')} | {_f(c['rank_diff'], '{:+d}')} |")
        L += ["", "Faculty AI flag: " + ", ".join(f"{e}={v}" for e, v in analysis["faculty_ai_flag"].items()) + ".", ""]
        for n in analysis["notes"]:
            L.append(f"- NOTE: {n}")
    else:
        L += ["## Scoring", "", "No scoring return ingested yet (`essay-grader study ingest-scores`).", ""]
    L += ["", "Not produced here (human or analysis stage, per the pre-registered plan): cross-exam random-effects pooling, I^2/Q, "
          "Holm-Bonferroni, moderators, faculty-flag rationale coding, the 'AI passed' determination.", ""]
    return "\n".join(L)


def cohort_dashboard(scoring_csv: Path) -> str:
    rows = list(csv.DictReader(scoring_csv.open(newline="", encoding="utf-8"))) if scoring_csv.is_file() else []
    L = ["# Cohort Results DRAFT (generated from scoring-results.csv)", "",
         "Generated by `essay-grader study report`. exam-taker's dashboard is human-curated; this is raw material for that "
         "curation. z-scores are against the real-student-only distribution (sample SD, n-1); rank is 1-indexed among real "
         "students. Effect = later arm z minus earlier arm z (the standardized materials effect, plan section 8.3).", ""]
    if not rows:
        return "\n".join(L + ["No rows yet."])
    arms: list[str] = []
    for r in rows:
        if r["arm"] not in arms:
            arms.append(r["arm"])
    arms.sort(key=lambda a: (a not in "ASB", "ASB".index(a) if a in "ASB" else 99, a))
    groups: dict[tuple, dict[str, dict]] = {}
    for r in rows:
        groups.setdefault((r["exam_date"], r["course"], r["professor"], r["model"]), {})[r["arm"]] = r
    pairs = [(arms[i], arms[j]) for i in range(len(arms)) for j in range(i)]
    head = ["Date", "Exam", "Model", "Real n"] + [f"{a} {x}" for a in arms for x in ("raw", "rank", "z")] + [f"Effect z {l}-{e}" for l, e in pairs] + ["Faculty flag"]
    L += ["| " + " | ".join(head) + " |", "|" + "|".join(["---"] * len(head)) + "|"]
    for (date_, course, prof, model), by_arm in sorted(groups.items()):
        any_r = next(iter(by_arm.values()))
        cells = [date_, f"{course} ({prof})", model, any_r["class_n_real"] or "n/a"]
        for a in arms:
            r = by_arm.get(a)
            cells += [r["total_score"] or "n/a", r["class_rank"] or "n/a", r["z_score"] or "n/a"] if r else ["-", "-", "-"]
        for later, earlier in pairs:
            try:
                cells.append(f"{float(by_arm[later]['z_score']) - float(by_arm[earlier]['z_score']):+.2f}")
            except (KeyError, ValueError):
                cells.append("n/a")
        cells.append(" / ".join(f"{a}: {by_arm[a]['faculty_ai_flag']}" for a in arms if a in by_arm))
        L.append("| " + " | ".join(cells) + " |")
    return "\n".join(L) + "\n"


def write_reports(design: Design, store: StudyStore, analysis: dict | None) -> list[Path]:
    out = []
    p = store.root / "report.md"
    p.write_text(study_report(design, store, analysis), encoding="utf-8")
    out.append(p)
    d = store.d("methodology")
    dp = d / "cohort-results.draft.md"
    dp.write_text(cohort_dashboard(d / "scoring-results.csv"), encoding="utf-8")
    out.append(dp)
    return out
